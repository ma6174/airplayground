#!/usr/bin/env python3
"""Turn still images into H.264 access units the firmware can send as-is.

Every image is encoded with x264 as a single IDR frame in Baseline profile, so
the device never needs an encoder: it just replays the bytes. The SPS/PPS shared
by all images become the AVCDecoderConfigurationRecord (avcC) that the receiver
needs before the first frame.

Usage:
    make_frames.py --out ../components/media/src/frames.c image1.png image2.png

Requires ffmpeg with libx264 on PATH.
"""

import argparse
import os
import shutil
import struct
import subprocess
import sys
import tempfile

# 1280x720 keeps text crisp on a TV without any per-device scaling surprises;
# the bitstream size of one IDR frame at this size is tens of kilobytes, which a
# single 16 MB flash handles with room to spare.
CANVAS = (1280, 720)


def run(cmd):
    result = subprocess.run(cmd, capture_output=True)
    if result.returncode != 0:
        sys.exit("command failed: %s\n%s" % (" ".join(cmd), result.stderr.decode(errors="replace")))
    return result.stdout


def encode(image):
    """Encode one image into a list of NAL units (start codes stripped)."""
    with tempfile.TemporaryDirectory() as work:
        out = os.path.join(work, "frame.h264")
        run([
            "ffmpeg", "-loglevel", "error", "-y",
            "-i", image,
            "-vf", "scale=%d:%d:flags=lanczos" % CANVAS,
            "-c:v", "libx264",
            "-profile:v", "baseline",
            "-pix_fmt", "yuv420p",
            "-x264-params", "keyint=1:min-keyint=1:scenecut=0:bframes=0:ref=1:crf=23",
            "-frames:v", "1",
            "-f", "h264", out,
        ])
        with open(out, "rb") as handle:
            data = handle.read()
    return split_annex_b(data)


def split_annex_b(data):
    """Split an Annex-B byte stream into NAL units without start codes."""
    starts = []
    index = 0
    while True:
        index = data.find(b"\x00\x00\x01", index)
        if index < 0:
            break
        starts.append(index + 3)
        index += 3

    nals = []
    for number, begin in enumerate(starts):
        end = starts[number + 1] - 3 if number + 1 < len(starts) else len(data)
        while end > begin and data[end - 1] == 0 and data[end - 2] == 0:
            end -= 1  # drop the leading zero of a four-byte start code
        nal = data[begin:end]
        if nal:
            nals.append(nal)
    return nals


def nal_type(nal):
    return nal[0] & 0x1F


def avcc_record(sps, pps):
    """AVCDecoderConfigurationRecord, with the four trailing bytes genuine
    senders append."""
    record = bytes([0x01, sps[1], sps[2], sps[3], 0xFF, 0xE1]) + struct.pack(">H", len(sps)) + sps
    record += bytes([0x01]) + struct.pack(">H", len(pps)) + pps
    return record + b"\x02\x00\x00\x00"


def avcc_access_unit(nals):
    out = b""
    for nal in nals:
        out += struct.pack(">I", len(nal)) + nal
    return out


def emit(path, sps, pps, frames, sources):
    avcc = avcc_record(sps, pps)
    lines = [
        "/* Generated by tools/make_frames.py - do not edit.",
        " *",
        " * %d still image(s) encoded as single-IDR Baseline access units at %dx%d." % (
            len(frames), CANVAS[0], CANVAS[1]),
        " * Sources:",
    ]
    for source in sources:
        lines.append(" *   - %s" % os.path.basename(source))
    lines += [" */", "", '#include "media_frames.h"', "", "#include <stddef.h>", "",
              "static const uint8_t *media_frame_at(size_t index, size_t *len);", "",
              "static const uint8_t s_avcc[] = {"]
    lines += byte_lines(avcc)
    lines.append("};")
    lines.append("")

    for index, frame in enumerate(frames):
        lines.append("static const uint8_t s_frame_%d[] = {" % index)
        lines += byte_lines(frame)
        lines.append("};")
        lines.append("")

    lines.append("static const uint8_t *const s_frames[] = {")
    for index in range(len(frames)):
        lines.append("    s_frame_%d," % index)
    lines.append("};")
    lines.append("static const size_t s_frame_lens[] = {")
    for index, frame in enumerate(frames):
        lines.append("    sizeof(s_frame_%d)," % index)
    lines.append("};")
    lines.append("")
    lines.append("static const airplay_frames_t s_source = {")
    lines.append("    .avcc = s_avcc,")
    lines.append("    .avcc_len = sizeof(s_avcc),")
    lines.append("    .width = %du," % CANVAS[0])
    lines.append("    .height = %du," % CANVAS[1])
    lines.append("    .frame_count = %du," % len(frames))
    lines.append("    .frame = media_frame_at,")
    lines.append("};")
    lines.append("")
    lines.append("static const uint8_t *media_frame_at(size_t index, size_t *len)")
    lines.append("{")
    lines.append("    if (index >= sizeof(s_frames) / sizeof(s_frames[0])) {")
    lines.append("        *len = 0;")
    lines.append("        return NULL;")
    lines.append("    }")
    lines.append("    *len = s_frame_lens[index];")
    lines.append("    return s_frames[index];")
    lines.append("}")
    lines.append("")
    lines.append("const airplay_frames_t *media_still_frames(void)")
    lines.append("{")
    lines.append("    return &s_source;")
    lines.append("}")
    lines.append("")

    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def byte_lines(data, per_line=16):
    out = []
    for start in range(0, len(data), per_line):
        chunk = data[start:start + per_line]
        out.append("    " + " ".join("0x%02x," % byte for byte in chunk))
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("images", nargs="+", help="PNG/JPEG still images")
    parser.add_argument("--out", required=True, help="generated C file")
    args = parser.parse_args()

    if shutil.which("ffmpeg") is None:
        sys.exit("ffmpeg not found on PATH")

    sps = pps = None
    frames = []
    for image in args.images:
        nals = encode(image)
        types = [nal_type(nal) for nal in nals]
        image_sps = next((nal for nal in nals if nal_type(nal) == 7), None)
        image_pps = next((nal for nal in nals if nal_type(nal) == 8), None)
        vcl = [nal for nal in nals if 1 <= nal_type(nal) <= 5]
        if image_sps is None or image_pps is None or not vcl:
            sys.exit("%s: encoder produced no SPS/PPS/slice (NAL types %s)" % (image, types))
        if sps is None:
            sps, pps = image_sps, image_pps
        elif image_sps != sps or image_pps != pps:
            sys.exit("%s: SPS/PPS differ from the first image; encode all images with "
                     "identical parameters" % image)
        frames.append(avcc_access_unit(vcl))
        print("%s: %d NAL(s) %s, access unit %d bytes" % (
            os.path.basename(image), len(vcl), types, len(frames[-1])))

    emit(args.out, sps, pps, frames, args.images)
    print("wrote %s (%d frame(s), avcC %d bytes)" % (args.out, len(frames), len(avcc_record(sps, pps))))


if __name__ == "__main__":
    main()
