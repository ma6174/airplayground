#!/usr/bin/env python3
"""Transcribes the Go-exported constants into the C component's data files.

Input:  fairplay_data.h, generated by the Go reference implementation
        (see the FairPlay port notes: emit_test.go writes it from fpsap*.go).
Output: src/fpsap_tables.c          white-box substitution/mix bases and the
                                   (base, in_xor, out_xor) lookup triples
        src/fp_data_sap.inc         SAP hash initial state and seed
        src/fp_data_md5.inc         modified-MD5 shift/constant tables
        src/fp_data_message.inc     SAS-CBC IVs, round keys, inverse S-box
        src/fp_data_fpsap.inc       protocol constants and network masks

Nothing here is retyped by hand: the numbers are copied from the exported
header, and the expanded white-box tables are hashed afterwards and compared
against the checksum the Go tests publish (90128 bytes /
28d0986abebe30458348dfa2957aa1d52d6f3ad5a9468c5d8a9c4139b7ca2b43).
"""

import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")
# fairplay_data.h is produced by tools/export_data.sh; pass another path as the
# first argument or set FAIRPLAY_DATA_H.
DEFAULT_INPUT = os.environ.get("FAIRPLAY_DATA_H", os.path.join(HERE, "fairplay_data.h"))
EXPECTED_TABLE_SHA256 = "28d0986abebe30458348dfa2957aa1d52d6f3ad5a9468c5d8a9c4139b7ca2b43"
EXPECTED_TABLE_BYTES = 90128

# Declarations that belong to the white-box tables file, kept with external
# linkage so both fpsap.c and the host test's table checksum can read them.
TABLE_NAMES = [
    "fpsap_first_input_mask",
    "fpsap_second_output_mask",
    "fpsap_substitution_bases",
    "fpsap_mix_bases",
    "fpsap_first_round",
    "fpsap_first_mix",
    "fpsap_first_final",
    "fpsap_second_round",
    "fpsap_second_mix",
    "fpsap_second_final",
]

# Everything else, split by the translation unit that needs it.
FRAGMENTS = {
    "fp_data_sap.inc": [
        "sap_initial_hash",
        "sap_initial_matrix",
        "sap_seed",
    ],
    "fp_data_md5.inc": [
        "fairplay_md5_shift",
        "fairplay_md5_constant",
    ],
    "fp_data_message.inc": [
        "fairplay_message_iv",
        "fairplay_round_key0",
        "fairplay_round_key10",
        "fairplay_middle_keys",
        "fairplay_inverse_sbox",
    ],
    "fp_data_fpsap.inc": [
        "fairplay_initial_session_key",
        "fairplay_kdf_prefix",
        "fairplay_kdf_suffix",
        "fpsap_m1_payload",
        "fpsap_m3_label",
        "fpsap_descriptor_prefix",
        "fpsap_descriptor_suffix",
        "fpsap_fixed_block",
        "fpsap_first_position_map",
        "fpsap_second_position_map",
    ],
}

DECL_RE = re.compile(
    r"static const (struct lookup|uint8_t|uint32_t)\s+(\w+)"
    r"((?:\[[0-9]+\])*)\s*=\s*\{(.*?)\n\};",
    re.S,
)
TRIPLE_RE = re.compile(r"\{(\d+),(0x[0-9a-fA-F]+),(0x[0-9a-fA-F]+)\}")


def parse(path):
    text = open(path, encoding="utf-8").read()
    decls = {}
    for ctype, name, dims, body in DECL_RE.findall(text):
        if name in decls:
            sys.exit(f"duplicate declaration: {name}")
        decls[name] = (ctype, dims, body)
    return decls


def lookup_triples(body):
    return [(int(a), int(b, 16), int(c, 16)) for a, b, c in TRIPLE_RE.findall(body)]


def expand_tables(decls):
    """Mirror of fpsap_test.go's table checksum: concatenate every expanded
    byte of every table so a single wrong digit changes the digest."""
    bases = {
        "subst": [[int(v, 16) for v in re.findall(r"0x([0-9a-f]{2})", decls[f"fpsap_substitution_bases"][2])][i * 256:(i + 1) * 256]
                  for i in range(6)],
        "mix": [[int(v, 16) for v in re.findall(r"0x([0-9a-f]{2})", decls[f"fpsap_mix_bases"][2])][i * 256:(i + 1) * 256]
                for i in range(7)],
    }
    out = bytearray()
    out += bytes(int(v, 16) for v in re.findall(r"0x([0-9a-f]{2})", decls["fpsap_first_input_mask"][2]))
    for network in ("first", "second"):
        rows = [lookup_triples(line) for line in decls[f"fpsap_{network}_round"][2].strip().splitlines()]
        if len(rows) != 9 or len(rows[0]) != 16:
            sys.exit(f"{network} round table shape {len(rows)}x{len(rows[0])}, want 9x16")
        for bank in range(9):
            for column in range(16):
                table, in_xor, out_xor = rows[bank][column]
                out += bytes(bases["subst"][table][v ^ in_xor] ^ out_xor for v in range(256))
        mix_rows = [lookup_triples(line) for line in decls[f"fpsap_{network}_mix"][2].strip().splitlines()]
        if len(mix_rows) != 4 or len(mix_rows[0]) != 4:
            sys.exit(f"{network} mix table shape {len(mix_rows)}x{len(mix_rows[0])}, want 4x4")
        for column in range(4):
            for value in range(256):
                for output_byte in range(4):
                    table, in_xor, out_xor = mix_rows[column][output_byte]
                    out.append(bases["mix"][table][value ^ in_xor] ^ out_xor)
        final = lookup_triples(decls[f"fpsap_{network}_final"][2])
        if len(final) != 16:
            sys.exit(f"{network} final table has {len(final)} entries, want 16")
        for column in range(16):
            table, in_xor, out_xor = final[column]
            out += bytes(bases["subst"][table][v ^ in_xor] ^ out_xor for v in range(256))
    return bytes(out)


def format_bytes(data, per_line=12):
    out = []
    for i in range(0, len(data), per_line):
        out.append("\t" + ", ".join(f"0x{v:02x}" for v in data[i:i + per_line]) + ",")
    return "\n".join(out)


def forward_sbox(decls):
    """The Go source only ships the inverse S-box; both the message cipher and
    the AES-128 block derive the forward direction by inverting it. Doing that
    here keeps a writable table out of the firmware."""
    inverse = [int(v, 16) for v in re.findall(r"0x([0-9a-f]{2})", decls["fairplay_inverse_sbox"][2])]
    if len(inverse) != 256 or sorted(inverse) != list(range(256)):
        sys.exit("fairplay_inverse_sbox is not a permutation")
    forward = [0] * 256
    for value, inv in enumerate(inverse):
        forward[inv] = value
    return forward


def emit_fragment(filename, names, decls, derived=None):
    path = os.path.join(SRC, filename)
    lines = [
        "/*",
        " * Generated by tools/gen_tables.py from the Go implementation's exported",
        " * constants. Do not edit: re-run the script.",
        " */",
        "",
    ]
    for name in names:
        ctype, dims, body = decls[name]
        lines.append(f"static const {ctype} {name}{dims} = {{{body}")
        lines.append("};")
        lines.append("")
    if derived:
        lines.extend(derived)
        lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def emit_tables(decls):
    path = os.path.join(SRC, "fpsap_tables.c")
    lines = [
        "/*",
        " * White-box tables of the FairPlay SAP exchange.",
        " *",
        " * Generated by tools/gen_tables.py from the Go implementation's exported",
        " * tables. Do not edit: re-run the script.",
        " *",
        " * The 13 permutation bases plus the (base, in_xor, out_xor) triples are the",
        " * exact representation the Go code uses; expanding them into 176 full",
        " * tables would cost 45 KiB of flash per network for the same result.",
        " */",
        '#include "fp_internal.h"',
        "",
    ]
    for name in TABLE_NAMES:
        ctype, dims, body = decls[name]
        ctype = "fp_lookup" if ctype == "struct lookup" else ctype
        lines.append(f"const {ctype} {name}{dims} = {{{body}")
        lines.append("};")
        lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_INPUT
    if not os.path.isfile(source):
        sys.exit(f"missing input header: {source}")
    decls = parse(source)

    known = set(TABLE_NAMES)
    for names in FRAGMENTS.values():
        known.update(names)
    unknown = set(decls) - known
    if unknown:
        sys.exit(f"unmapped declarations in {source}: {sorted(unknown)}")
    missing = known - set(decls)
    if missing:
        sys.exit(f"declarations missing from {source}: {sorted(missing)}")

    expanded = expand_tables(decls)
    if len(expanded) != EXPECTED_TABLE_BYTES:
        sys.exit(f"expanded table size {len(expanded)}, want {EXPECTED_TABLE_BYTES}")
    digest = hashlib.sha256(expanded).hexdigest()
    if digest != EXPECTED_TABLE_SHA256:
        sys.exit(f"expanded table sha256 {digest}, want {EXPECTED_TABLE_SHA256}")

    emit_tables(decls)
    derived = {
        "fp_data_message.inc": [
            "/* Derived from fairplay_inverse_sbox: forward_sbox[inverse_sbox[e]] = e,",
            " * the same inversion the reference implementation performs at start-up. */",
            "static const uint8_t fairplay_forward_sbox[256] = {",
            format_bytes(forward_sbox(decls)),
            "};",
        ]
    }
    for filename, names in FRAGMENTS.items():
        emit_fragment(filename, names, decls, derived.get(filename))
    print(f"tables verified: {len(expanded)} bytes, sha256 {digest}")
    print("wrote src/fpsap_tables.c and", ", ".join(sorted(FRAGMENTS)))


if __name__ == "__main__":
    main()
