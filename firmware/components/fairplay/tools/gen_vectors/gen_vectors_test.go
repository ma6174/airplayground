func gvHex(b []byte) string {
	const digits = "0123456789abcdef"
	var sb strings.Builder
	for _, v := range b {
		sb.WriteByte(digits[v>>4])
		sb.WriteByte(digits[v&15])
	}
	return sb.String()
}

func gvMustHex(s string) []byte {
	out := make([]byte, len(s)/2)
	for i := range out {
		_, err := fmt.Sscanf(s[2*i:2*i+2], "%02x", &out[i])
		if err != nil {
			panic(err)
		}
	}
	return out
}

